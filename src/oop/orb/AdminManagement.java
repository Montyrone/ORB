         int selectedRow = jTable1.getSelectedRow();
         if (selectedRow == -1) {
             JOptionPane.showMessageDialog(this, "Please select a user to update.", "Error", JOptionPane.ERROR_MESSAGE);
             return;
         }

         // Get the current username from the selected row (assuming username is in the first column)
         String currentUserName = (String) jTable1.getValueAt(selectedRow, 0); 

         // Prompt the user to choose a new role
         String[] roles = {"user", "VIP"};
         String newRole = (String) JOptionPane.showInputDialog(
             this,
             "Select the new role for " + currentUserName + ":",
             "Change Role",
             JOptionPane.QUESTION_MESSAGE,
             null,
             roles,
             "user" // Default role
         );

         if (newRole == null) {
             return; // No role selected, exit
         }

         // Confirm the role change
         int confirmation = JOptionPane.showConfirmDialog(
             this,
             "Are you sure you want to change the role of \"" + currentUserName + "\" to \"" + newRole + "\"?",
             "Confirm Role Change",
             JOptionPane.YES_NO_OPTION
         );

         if (confirmation == JOptionPane.YES_OPTION) {
             // Update the role in the database
             try (Connection conn = DBConnect.getConnection();
                  PreparedStatement stmt = conn.prepareStatement(
                      "UPDATE users SET role = ? WHERE fullname = ?")) {

                 stmt.setString(1, newRole); // Set new role
                 stmt.setString(2, currentUserName); // Set current username
                 int rowsAffected = stmt.executeUpdate();

                 if (rowsAffected > 0) {
                     // If role update is successful, update the JTable
                     jTable1.setValueAt(newRole, selectedRow, 1); // Update the role in the second column of the table
                     JOptionPane.showMessageDialog(this, "User role updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                 } else {
                     JOptionPane.showMessageDialog(this, "Error updating the user role in the database.", "Error", JOptionPane.ERROR_MESSAGE);
                 }
             } catch (SQLException e) {
                 e.printStackTrace();
                 JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
             }
         }
