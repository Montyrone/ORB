    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // Get the selected row index
        int selectedRow = jTable1.getSelectedRow();

        // Check if a row is selected
        if (selectedRow != -1) {
            // Get the item name from the first column
            String selectedItem = (String) jTable1.getValueAt(selectedRow, 0);

            // Construct the file path using the selected item and the current directory
            String filePath = currentDirectory.getPath() + "/" + selectedItem;

            File file = new File(filePath);

            // Check if the selected item is a directory
            if (file.isDirectory()) {
                // If it's a folder, navigate into it and reload the table
                parentDirectory = currentDirectory;  // Store the current directory as the parent
                currentDirectory = file;  // Update the current directory to the selected folder
                loadUserFolders();  // Reload the table to show the contents of the folder
            } else if (file.exists()) {
                // If it's a PDF file, open it
                try {
                    Desktop.getDesktop().open(file);  // Open the PDF file if it exists
                } catch (IOException e) {
                    e.printStackTrace();
                    JOptionPane.showMessageDialog(this, "Error opening PDF.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } else {
                // If neither a file nor folder, show an error
                JOptionPane.showMessageDialog(this, "The selected item does not exist.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            // If no item is selected, show an error
            JOptionPane.showMessageDialog(this, "No item selected.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

