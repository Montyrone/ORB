    private void startClock() {
        timer = new Timer(1000, (ActionEvent e) -> {
            String currentTime = getCurrentTime();
            jLabel2.setText(currentTime); // Update jLabel2 with the current time
        });
        timer.start(); // Start the timer
    }

    private String getCurrentTime() {
        SimpleDateFormat sdf = new SimpleDateFormat("HH:mm:ss");
        return sdf.format(new Date());
    }

    private void loadUserFolders() {
        if (currentDirectory != null && currentDirectory.exists()) {
            // Get all the subdirectories (user folders) and PDF files inside the current directory
            File[] files = currentDirectory.listFiles(file -> file.isDirectory() || file.getName().endsWith(".pdf"));

            // Update JTable to display folder names and PDFs
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); // Clear existing rows

            // If we're inside a user folder, allow going back to the parent folder
            if (parentDirectory != null) {
                model.addRow(new Object[] { ".." }); // Add ".." to go back to the parent folder
            }

            // Add user folders and PDFs to the table
            for (File file : files) {
                model.addRow(new Object[] { file.getName() });
            }
        } else {
            JOptionPane.showMessageDialog(this, "Current directory is invalid or does not exist.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    
